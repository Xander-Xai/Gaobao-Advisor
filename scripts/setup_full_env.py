"""Generate .env.full for the optional MySQL + Redis + worker profile.

    python scripts/setup_full_env.py
    docker compose --env-file .env.full \\
      -f docker-compose.yml -f docker-compose.full.yml --profile full up --build

The file is local-only (gitignored), mode 0600, and prints the generated admin
password once. It never writes the real password into the repository.
"""

from __future__ import annotations

import argparse
import json
import os
import secrets
import stat
import sys
from pathlib import Path

from server.admin.auth import hash_password


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate .env.full for the full docker profile")
    parser.add_argument("--out", default=".env.full")
    parser.add_argument("--username", default="operator")
    parser.add_argument("--role", default="operator", choices=["viewer", "operator", "admin"])
    parser.add_argument("--force", action="store_true")
    parser.add_argument("--add-java-reader", action="store_true", help="Safely extend an existing .env.full")
    args = parser.parse_args(argv)

    out = Path(args.out)
    if args.add_java_reader:
        if not out.is_file():
            print(f"{out} missing; generate it first", file=sys.stderr)
            return 2
        original = out.read_text(encoding="utf-8")
        if any(line.startswith("CATALOG_READ_PASSWORD=") for line in original.splitlines()):
            print(f"{out} already contains CATALOG_READ_PASSWORD")
            return 0
        with out.open("a", encoding="utf-8") as output:
            output.write(f"CATALOG_READ_PASSWORD={secrets.token_hex(24)}\n")
        os.chmod(out, stat.S_IRUSR | stat.S_IWUSR)
        print(f"extended {out} with a Java Catalog read-only secret (mode 0600)")
        return 0

    if out.exists() and not args.force:
        print(f"{out} already exists; use --force to overwrite", file=sys.stderr)
        return 2

    admin_password = secrets.token_urlsafe(18)
    admin_hash = hash_password(admin_password)
    token_secret = secrets.token_hex(32)
    session_secret = secrets.token_hex(32)
    mysql_password = secrets.token_urlsafe(24)
    mysql_root = secrets.token_urlsafe(24)
    catalog_password = secrets.token_hex(24)
    users = [{"username": args.username, "password_hash": admin_hash, "role": args.role}]

    lines = [
        "# generated by scripts/setup_full_env.py — local full-profile only",
        "MYSQL_DATABASE=gaobao",
        "MYSQL_USER=gaobao",
        f"MYSQL_PASSWORD={mysql_password}",
        f"MYSQL_ROOT_PASSWORD={mysql_root}",
        f"CATALOG_READ_PASSWORD={catalog_password}",
        f"DATABASE_URL=mysql+pymysql://gaobao:{mysql_password}@mysql:3306/gaobao?charset=utf8mb4",
        "REDIS_URL=redis://redis:6379/0",
        "AUTO_MIGRATE=true",
        "AUTO_SEED_DEMO=true",
        "QUALITY_TASK_MODE=async",
        "ADMIN_RATE_LIMIT_BACKEND=redis",
        f"ADMIN_USERS_JSON='{json.dumps(users, separators=(',', ':'))}'",
        f"ADMIN_TOKEN_SECRET={token_secret}",
        f"SESSION_SECRET={session_secret}",
        "APP_ENV=development",
    ]
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    os.chmod(out, stat.S_IRUSR | stat.S_IWUSR)
    print(f"wrote {out} (mode 0600)")
    print(f"admin username: {args.username}")
    print(f"admin password: {admin_password}")
    print(
        "start: docker compose --env-file .env.full -f docker-compose.yml -f docker-compose.full.yml --profile full up --build"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
